const LOOKUP = new Map(COUNTRIES);

function normalize(value: string) {
  return value
    .toLowerCase()
    .replace(/[.]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

export function inferCountry(location: string | null | undefined): string | null {
  if (!location) return null;
  const parts = location
    .split(/[,|/]/)
    .map((part) => normalize(part))
    .filter(Boolean);

  for (const part of [...parts].reverse()) {
    const hit = LOOKUP.get(part);
    if (hit) return hit;
  }

  const blob = normalize(location);
  for (const [key, name] of COUNTRIES) {
    if (key.length < 3) continue;
    if (blob === key || blob.endsWith(` ${key}`) || blob.includes(` ${key} `)) {
      return name;
    }
  }
  return null;
}
